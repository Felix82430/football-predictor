def _strip_accents(text: str) -> str:
    """剥离西语/德语/法语/北欧重音符号（如 Alavés -> Alaves, Málaga -> Malaga）"""
    nfkd = unicodedata.normalize("NFKD", text)
    return "".join(ch for ch in nfkd if not unicodedata.combining(ch))


def _clean_key(name: str) -> str:
    s = _strip_accents(name).strip().lower()
    s = re.sub(r"\s+", " ", s)
    return s


def normalize_team_name(raw_name: str) -> str:
    """将任意数据源的球队名规整为标准英文名"""
    if not raw_name:
        return ""
    raw = raw_name.strip()
    if raw in CANONICAL_TO_CN:
        return raw
    key = _clean_key(raw)
    if key in ALIAS_MAP:
        return ALIAS_MAP[key]
    # 去掉常见前后缀再尝试
    stripped = re.sub(
        r"\b(fc|cf|sc|ac|as|rc|rcd|cd|ud|sd|ss|ssc|afc|sv|vfl|vfb|tsg|fsv|fk|sk|skc|bk|if|07|04|05|1846|1899)\b",
        "",
        key,
    ).strip()
    stripped = re.sub(r"\s+", " ", stripped)
    if stripped in ALIAS_MAP:
        return ALIAS_MAP[stripped]
    for canon in CANONICAL_TO_CN:
        c_key = _clean_key(canon)
        if c_key == key or c_key == stripped:
            return canon
    # 模糊匹配（高阈值防误配）
    canon_keys = {_clean_key(k): k for k in CANONICAL_TO_CN}
    candidates = get_close_matches(key, list(canon_keys.keys()), n=1, cutoff=0.86)
    if candidates:
        return canon_keys[candidates[0]]
    return raw


def to_cn_name(team_name: str) -> str:
    canon = normalize_team_name(team_name)
    return CANONICAL_TO_CN.get(canon, canon)
